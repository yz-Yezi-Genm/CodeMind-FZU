metadata = MetaData(naming_convention={
    'pk':'pk_%(table_name)s', 'fk':'fk_%(table_name)s_%(column_0_N_name)s_%(referred_table_name)s',
    'uq':'uq_%(table_name)s_%(column_0_N_name)s', 'ck':'ck_%(table_name)s_%(constraint_name)s',
    'ix':'ix_%(table_name)s_%(column_0_name)s'})
mapper_registry = registry(metadata=metadata)
json_type = JSON().with_variant(JSONB(), 'postgresql')

def col(name, typ, meaning, *, nullable=False, fk=None, unique=False, default=None, pk=False):
    args = [ForeignKey(fk, ondelete='RESTRICT')] if fk else []
    kw = dict(nullable=nullable, primary_key=pk, unique=unique, comment=meaning)
    if default is not None:
        kw['server_default'] = text(default)
    return Column(name, typ, *args, **kw)

def ident():
    return Column('id', Uuid, primary_key=True, default=uuid4, comment='内部UUID；应用生成')

def ref(name, target, meaning, nullable=False):
    return col(name, Uuid, meaning, nullable=nullable, fk=target+'.id')

def state(name, meaning, default):
    return col(name, String(32), meaning, default="'"+default+"'")

def choice(field, *values):
    return CheckConstraint(field+' IN ('+', '.join("'"+v+"'" for v in values)+')', name=field+'_values')

def table(name, meaning, *items):
    return Table(name, metadata, *items,
        col('created_at', DateTime(timezone=True), '创建时间', default='CURRENT_TIMESTAMP'),
        col('updated_at', DateTime(timezone=True), '更新时间；更新操作须显式维护', default='CURRENT_TIMESTAMP'),
        comment=meaning)

